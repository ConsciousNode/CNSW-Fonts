function validateGrid(rows, w, h, code, name) {
  if (!Array.isArray(rows) || rows.length !== h) {
    throw new Error(`${name} code ${code}: expected ${h} rows, got ${rows ? rows.length : 'null'}`);
  }
  for (let r = 0; r < h; r++) {
    if (typeof rows[r] !== 'string' || rows[r].length !== w) {
      throw new Error(`${name} code ${code} row ${r}: expected length ${w}, got ${rows[r]}`);
    }
  }
  return rows;
}

// Apply balanced-ternary shadow rule to an 8x8 ink grid -> 9x9 ("+" / "0" / "-")
function applyShadowRule(inkRows) {
  const out = [];
  for (let r = 0; r < 9; r++) {
    let line = '';
    for (let c = 0; c < 9; c++) {
      const isInk = r < 8 && c < 8 && inkRows[r][c] === '#';
      if (isInk) {
        line += '+';
      } else {
        const upLeftInk = r > 0 && c > 0 && inkRows[r - 1][c - 1] === '#';
        line += upLeftInk ? '-' : '0';
      }
    }
    out.push(line);
  }
  return out;
}

